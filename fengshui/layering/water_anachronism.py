"""实测：用现代 DEM 水系评价古代都邑，年代越早失真越大。
   洛阳盆地五座都邑年代跨 2000 年，洛河/伊河多次改徙。"""
import sys
sys.path.insert(0, '/home/user/fs')
import luantou as L, kvamme as K

SITES = [('二里头（夏）',   -1750, 34.6961, 112.6906),
         ('偃师商城（商）', -1600, 34.7167, 112.7833),
         ('东周王城',        -770, 34.6710, 112.4210),
         ('汉魏洛阳故城',      25, 34.7256, 112.5747),
         ('隋唐洛阳城',       605, 34.6620, 112.4530)]

reg = K.Mosaic('洛阳', range(34, 35), range(112, 113))
print(f"{'遗址':<16}{'年代':>7}{'距今水系 m':>11}{'垂直落差 m':>11}{'水系汇水 km²':>13}")
for n, y, la, lo in SITES:
    m = L.metrics(reg, la, lo)
    print(f"{n:<16}{y:>7}{m['d_water']:>11.0f}{m['dh_water']:>11.1f}{m['river_km2']:>13.1f}")
print("""
五座都邑无一不是傍洛河而建（文献与考古皆确凿）。
前三座今日算出「距水 2.4-2.6 km、汇水 0.0 km²」——匹配到的不是洛河，是提取出的小沟。
而平原模式下 water + water_gate = 0.48，接近一半权重落在这个已失真的量上。""")
